"""
Generate t16_flags.s + t16_flags.json: flag and condition truth table.
For each scenario (an instruction producing known flags) record %hwflag,
%shwflag, then for every branch condition and every cexe condition whether it
was taken / executed (1/0). Results at OUT = SCRATCH + 0x100, 28 words each.
"""
import json

SCEN = [('cmp', 5, 3), ('cmp', 3, 5), ('cmp', 5, 5), ('cmp', 0x8000, 1), ('cmp', 0x7FFF, 0xFFFF),
        ('cmp', 0, 1), ('cmp', 0xFFFF, 1), ('add', 0xFFFF, 1), ('add', 0x7FFF, 1), ('add', 1, 1),
        ('add', 0x8000, 0x8000), ('sub', 0, 1)]
BR = ['bz', 'bnz', 'bge', 'blt', 'bgt', 'ble', 'bov', 'bnov', 'bc', 'bnc']
CX = ['nv', 'v', 'ngv', 'gv', 'nsv', 'sv', 'ngsv', 'gsv', 'nc', 'c', 'lt', 'ge', 'le', 'gt', 'nz', 'z']


def main():
    L = ['; generated by gen_t16.py', '        .equ TEST_ID, 0x0016', '        .include "common.inc"',
         'OUT = SCRATCH + 0x100', '        .include "prologue.inc"',
         '        mov a5,lo(OUT)', '        movhw a5,hi(OUT)']
    n = 0
    for k, (op, x, y) in enumerate(SCEN):
        setf = ['mov.l r1,0x%04X' % x, 'mov.l r2,0x%04X' % y, '%s r1,r2' % op]
        L.append('; ---- scenario %d: %s 0x%04X,0x%04X' % (k, op, x, y))
        L += ['        ' + s for s in setf]
        L += ['        mov r13,%hwflag', '        mov r14,%shwflag', '        stu r13,a5,1', '        stu r14,a5,1']
        for b in BR:
            n += 1
            L += ['        ' + s for s in setf]
            L += ['        %s t%d' % (b, n), '        mov.l r4,0', '        br d%d' % n,
                  't%d:    mov.l r4,1' % n, 'd%d:    stu r4,a5,1' % n]
        for c in CX:
            L += ['        mov.l r4,0'] + ['        ' + s for s in setf]
            L += ['        cexe (%s,nu) { } !1' % c, '        mov.l r4,1', '        stu r4,a5,1']
    L.append('        .include "epilogue.inc"')
    open('t16_flags.s', 'w').write('\n'.join(L) + '\n')
    json.dump({'scen': SCEN, 'br': BR, 'cx': CX}, open('t16_flags.json', 'w'))
    print('%d scenarios' % len(SCEN))


main()
