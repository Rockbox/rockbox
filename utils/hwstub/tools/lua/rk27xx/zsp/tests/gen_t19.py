"""Generate t19_jump_<n>.s: indirect jumps, one per image (may run away).
EXTRA+0 = 0x1111 before the jump, EXTRA+1 = 0x0BAD if execution fell through,
EXTRA+2 = 0x2222 if the target was reached."""
import json

J = [('pc_r_lo', ['mov.l r8,tgt', 'mov.l r9,0', 'mov.e %pc,r8']),
     ('pc_r_hi', ['mov.l r8,0', 'mov.l r9,tgt', 'mov.e %pc,r8']),
     ('pc_a_lo', ['mov a2,tgt', 'mov.e %pc,a2']),
     ('pc_a_hi', ['mov a2,0', 'movhw a2,tgt', 'mov.e %pc,a2']),
     ('call_a', ['mov a2,tgt', 'call a2']),
     ('reti', ['mov.l r8,tgt', 'mov %tpc,r8', 'nop', 'nop', 'reti'])]


def main():
    for i, (name, seq) in enumerate(J):
        L = ['; generated by gen_t19.py: %s' % name, '        .equ TEST_ID, 0x0190 + %d' % i,
             '        .include "common.inc"', '        .include "prologue.inc"',
             '        mov.l r13,0x1111', '        st r13,a7,0x40']
        L += ['        ' + x for x in seq]
        L += ['        mov.l r13,0x0BAD', '        st r13,a7,0x41',
              'tgt:    mov.l r13,0x2222', '        st r13,a7,0x42',
              '        mov r10,%rpc', '        mov r11,%tpc', '        mov r12,%pc',
              '        .include "epilogue.inc"']
        open('t19_jump_%d.s' % i, 'w').write('\n'.join(L) + '\n')
    json.dump([n for n, _ in J], open('t19_jump.json', 'w'))
    print('%d jump tests' % len(J))


main()
