"""Generate t8_alu.s + t8_alu.json: run every ALU table entry on fixed inputs."""
import json
A, B = 0x9234, 0x0003
M = 0xffff
def s16(v): return v - 0x10000 if v & 0x8000 else v
EXPECT = {   # obvious semantics only; others are recorded for inspection
    'add': lambda a, b: (a + b) & M, 'sub': lambda a, b: (a - b) & M,
    'and': lambda a, b: a & b, 'or': lambda a, b: a | b, 'xor': lambda a, b: a ^ b,
    'shll': lambda a, b: (a << b) & M, 'shla': lambda a, b: (a << b) & M, 'shrl': lambda a, b: a >> b,
    'shra': lambda a, b: (s16(a) >> b) & M,
    'min': lambda a, b: a if s16(a) < s16(b) else b, 'max': lambda a, b: a if s16(a) > s16(b) else b,
    'mov': lambda a, b: b, 'not': lambda a, b: ~b & M, 'neg': lambda a, b: -b & M,
    'abs': lambda a, b: abs(s16(b)) & M,
}
cases = []
for op in ['shll', 'shrl', 'shla', 'shra', 'shbl', 'shba', 'and', 'or', 'xor', 'add', 'sub',
           'min', 'max', 'iadd', 'isub', 'revb']:          # Cxxx ops_eacc, r1 = r1 op r2
    cases.append(('%s r1,r2' % op, A, B, op))
for op in ['not', 'mov', 'norm', 'abs', 'neg']:             # B0xx ops_eaac, r1 = op r2
    cases.append(('%s r1,r2' % op, A, 0x8003, op))
for op in ['shll', 'shrl', 'shla', 'shra', 'add', 'iadd']:  # A8xx ops_ea8c, r1 = r1 op imm4
    cases.append(('%s r1,3' % op, A, 3, op))
for op in ['add', 'sub']:                                   # FBxx three-operand, r1 = r2 op r3
    cases.append(('%s r1,r2,r3' % op, A, B, op))
src = ['; generated by gen_t8.py: ALU table entries on fixed inputs',
       '; result i (r1 after the op) is stored at EXTRA + i',
       '        .equ TEST_ID, 0x0008', '        .include "common.inc"', '        .include "prologue.inc"']
meta = []
for i, (txt, a, b, op) in enumerate(cases):
    three = txt.count(',') == 2
    src += ['        mov.l r1,0x%04X' % a, '        mov.l r2,0x%04X' % (a if three else b)]
    if three:
        src.append('        mov.l r3,0x%04X' % b)
    src += ['        ' + txt, '        pst st r1,a7,0x%X' % (0x40 + i)]
    f = EXPECT.get(op)
    unary = txt.split()[0] in ('not', 'mov', 'norm', 'abs', 'neg') and three is False and 'r2' in txt
    if f is None:
        exp = None
    elif unary:
        exp = f(a, b)              # result depends on the source operand only
    else:
        exp = f(a, b)              # r1 op r2/imm, or r2 op r3 for three-operand forms
    meta.append({'i': i, 'insn': txt, 'r1': a, 'r2': (a if three else b), 'r3': b if three else None, 'expect': exp})
src.append('.include "epilogue.inc"')
open('t8_alu.s', 'w').write('\n'.join(src) + '\n')
json.dump(meta, open('t8_alu.json', 'w'), indent=1)
print(len(cases), 'cases')
