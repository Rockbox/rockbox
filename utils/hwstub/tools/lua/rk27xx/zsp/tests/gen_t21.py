# t34_sdbuf: SDRAM write buffer depth and drain time, starting each case
# with an empty buffer. Same parameter block as t33 (a3 = window address).
# Per case 5 words at OUT + 1 + 5*i: store cycles, drain cycles (load + use
# of the last stored halfword), first value read back, last value read back,
# 0xC000 + i. Case i stores value 0x1000 + i (st) or pairs (0x2000 + i,
# 0x3000 + i) (std), from byte offset 0 of the block.
T34_N = [1, 2, 4, 8, 12, 16, 20, 24, 32, 48]
T34 = [('st', n) for n in T34_N] + [('std', n) for n in T34_N]


def t34():
    L = ['; generated by gen_t21.py: SDRAM write buffer depth and drain time',
         '        .equ TEST_ID, 0x0034'] + HEAD + ['        .include "prologue.inc"'] + PROLOGUE[2:]
    L += ['PARAM = DMEM_DSP + 0x7F0',
          '        mov a6,lo(EXTRA)', '        movhw a6,hi(EXTRA)',
          '        mov a1,lo(PARAM)', '        movhw a1,hi(PARAM)',
          '        ld r0,a1,0', '        ld r1,a1,1', '        ldd a3,a1,2',
          '        mov n0,r0',
          '        mov a0,0x0000', '        movhw a0,0x00CE',
          '        nop', '        nop',
          '        stx r1,a0',
          '        nop', '        nop',
          '        ldx r2,a0', '        stu r2,a5,1',
          '        mov.l r0,0x0080', '        mov %tc,r0']
    for i, (op, n) in enumerate(T34):
        if op == 'st':
            body = ['st r1,a3,0x%X' % k for k in range(n)]
            last = n - 1
            val = ['        mov.l r1,0x%04X' % (0x1000 + i)]
        else:
            body = ['std r4,a3,0x%X' % (2 * k) for k in range(n)]
            last = 2 * n - 1
            val = ['        mov.l r4,0x%04X' % (0x2000 + i), '        mov.l r5,0x%04X' % (0x3000 + i)]
        L += ['; ---- %d: %d x %s' % (i, n, op),
              '        mov.l r0,%d' % i, '        st r0,a6,0'] + val + [
              '        ld r15,a3,0x1F0', '        mov r15,r15',         # drain: buffer empty
              '        mov.l r0,0xFFFF', '        mov %timer0,r0',
              '        nop', '        nop', '        nop', '        nop',
              '        mov r13,%timer0'] + ['        ' + b for b in body] + [
              '        mov r14,%timer0',
              '        ld r2,a3,0x%X' % last, '        mov r3,r2',  # drain + read back last
              '        mov r12,%timer0',
              '        ld r8,a3,0', '        mov r8,r8',
              '        sub r13,r14', '        sub r14,r12',
              '        stu r13,a5,1', '        stu r14,a5,1', '        stu r8,a5,1', '        stu r3,a5,1',
              '        mov.l r0,0x%04X' % (0xC000 + i), '        stu r0,a5,1']
    L += marker(0xE34D)
    L.append('        .include "epilogue.inc"')
    return L


