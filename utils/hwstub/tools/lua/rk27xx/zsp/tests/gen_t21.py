# Images with a real vector table (no prologue.inc: it has .org 0).
def vec_image(test_id, title, handlers, main_body):
    """handlers: {source n: label} for vector 0x80 - 8n (n = 15: NMI at
    0x08). Other vectors go to 'spur', which records %ireq/%tpc at EXTRA+60
    and dumps. Code starts at 0x100."""
    L = ['; generated by gen_t21.py: ' + title,
         '        .equ TEST_ID, 0x%04X' % test_id] + HEAD
    L += ['        .org 0', '        br main']
    for n in range(16):
        L += ['        .org 0x%02X' % (0x80 - 8 * n), '        br %s' % handlers.get(n, 'spur')]
    L += ['        .org 0x100',
          'spur:   mov r1,%ireq', '        mov r2,%tpc', '        mov.l r3,0x5B00',
          '        st r3,a7,0x7C', '        st r1,a7,0x7D', '        st r2,a7,0x7E',
          '        br dump',
          'main:   mov a7,lo(RES)', '        movhw a7,hi(RES)',
          '        st r0,a7,STORE_DUMMY', '        st r0,a7,STORE_DUMMY'] + PROLOGUE[2:]
    L += main_body
    L.append('        .include "epilogue.inc"')
    return L


