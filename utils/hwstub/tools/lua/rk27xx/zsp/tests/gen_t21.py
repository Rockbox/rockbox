              '        nop', '        nop',
              '        mov.l r0,0x1000', '        mov %ireq,r0',
              '        nop', '        nop', '        nop', '        nop',
              '        mov r3,%smode', '        mov r4,%psmode', '        mov r5,%imask',
              '        mov.l r0,0', '        mov %imask,r0', '        mov %smode,r0',
