          '        mov.l r0,0x00C1', '        st r0,a1,3',        # EPR[3]: DWDMA
          '        mov a2,0x8000', '        movhw a2,0x00D7',
          '        mov a1,lo(PARAM)', '        movhw a1,hi(PARAM)',
