# t47_prio2: priority levels, the source-14-first effect and %ip0[15:14].
# (name, {source: level}, %ip0[15:14], raised sources mask, raise with the
# global enable already on)
def ip_regs(levels, top=0):
    ip0, ip1 = top << 14, 0
    for k, lv in levels.items():
        if k < 8:
            ip1 |= lv << (2 * k)
        else:
            ip0 |= lv << (2 * (k - 8))
    return ip0, ip1


