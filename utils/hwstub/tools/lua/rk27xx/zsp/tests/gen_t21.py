# t38_armirq: DSP -> ARM signals, with a handshake through DMEM 0x7F8
# (the ARM writes 1, then 2). Parameters at DMEM 0x7F0: [4,5] = CHIPCFG as
# the ARM read it. EXTRA+1 = phase reached.
#   phase 1: C2H0 = 0x11112222, C2H0b = 0x33334444 (mailbox, EPR[2] = 0x0C0)
#   phase 2: read SCU CHIPCFG (bus 0x1881C028: EPR[0] = 0x0C4, DSP 0xD0E014);
#            if it equals the ARM's value, set bit 17
#   phase 3: clear bit 17 again
# OUT: CHIPCFG read (lo, hi), written (hi), read back (lo, hi), 0xE38D.
def t38():
    M = ['PARAM = DMEM_DSP + 0x7F0',
         '        mov a6,lo(EXTRA)', '        movhw a6,hi(EXTRA)',
         '        mov a1,0x0000', '        movhw a1,0x00CE',
         '        mov.l r0,0x00C0', '        st r0,a1,2',
         '        mov.l r0,0x00C4', '        st r0,a1,0',
         '        mov a2,0x4000', '        movhw a2,0x00D4',          # mailbox
         '        mov a3,0xE014', '        movhw a3,0x00D0',          # SCU CHIPCFG
         '        mov a1,lo(PARAM)', '        movhw a1,hi(PARAM)',
         '; ---- phase 1: mailbox C2H0',
         '        mov.l r4,0x2222', '        mov.l r5,0x1111', '        std r4,a2,0x28',
         '        mov.l r4,0x4444', '        mov.l r5,0x3333', '        std r4,a2,0x2A',
         '        ldd r4,a2,0x20', '        mov r4,r4',               # drain
         '        mov.l r0,1', '        st r0,a6,1',
         'h1:     ld r0,a1,8', '        cmp r0,1', '        bnz h1',
         '; ---- phase 2: CHIPCFG bit 17 (only if the read matches the ARM\'s value)',
         '        ldd r4,a3',
         '        ldd r6,a1,4',
         '        stu r4,a5,1', '        stu r5,a5,1',
         '        mov.l r8,0',
         '        cmp r4,r6', '        bnz skip', '        cmp r5,r7', '        bnz skip',
         '        or r5,0x0002',
         '        std r4,a3',
         '        mov r8,r5',
         'skip:   stu r8,a5,1',
         '        ldd r4,a3', '        stu r4,a5,1', '        stu r5,a5,1',
         '        mov.l r0,2', '        st r0,a6,1',
         'h2:     ld r0,a1,8', '        cmp r0,2', '        bnz h2',
         '; ---- phase 3: clear bit 17',
         '        cmp r8,0', '        bz done3',
         '        ldd r4,a3', '        and r5,0xFFFD', '        std r4,a3',
         '        ldd r4,a3', '        mov r4,r4',
         'done3:  mov.l r0,3', '        st r0,a6,1']
    M += marker(0xE38D)
    return vec_image(0x0038, 'DSP -> ARM: mailbox and CHIPCFG bit 17', {}, M)


# t39_circ: every combination of the writable %amode bits (0-6, 8-11).
# All four circular buffers = [B, B+3] (set with mov.e). For each value,
# a0-a4 and a6 start at B and are post-incremented 6 times (ldu +1, then
# ldxu +n with n = 1); a register that does not end at B+6 counts as
# wrapped. Logged at OUT: %amode value, ldu mask, ldxu mask (bit k = aK),
