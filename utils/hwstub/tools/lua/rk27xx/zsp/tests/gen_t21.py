              '        mov.l r0,15', '        mov %loop1,r0',      # poll limit 16 x 64K
              '        ldd r4,a2,%s' % dw('CTL3H'),                # drain the write buffer
              '        mov r4,r4',
              '        mov.l r0,0xFFFF', '        mov %timer0,r0',
              '        nop', '        nop', '        nop', '        nop',
              '        mov r13,%timer0',
              '        mov.l r4,0x0808', '        mov.l r5,0',
