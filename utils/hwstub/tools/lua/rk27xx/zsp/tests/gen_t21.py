# t44_brevst: bit-reversed stores (%amode bit 1, width in bits 6:2).
# (name, reg, w, dest, n, copy): case 'copy' loads linearly through a0 from
# 0xB00 (values 0x200 + k) and stores through aR. Otherwise stores 0x100 + 0x10*case + k.
# Address trace (low(aR) - dest after each store) at 0x800.. in case order.
T44 = [('a4 w=3', 4, 3, 0xC00, 8, False), ('a5 w=3', 5, 3, 0xC10, 8, False),
       ('a4 w=4', 4, 4, 0xC20, 16, False), ('copy a0 -> a4 w=3', 4, 3, 0xC40, 8, True)]


def t44():
    M = ['        mov a6,0x0800', '        movhw a6,0',
         '        mov a0,0x0B00', '        movhw a0,0',
         '        mov.l r0,0x0200', '        mov.l r1,7', '        mov %loop0,r1',
         'src:    stu r0,a0,1', '        add r0,1', '        agn0 src']
    for c, (name, r, w, dest, n, copy) in enumerate(T44):
        v = 2 | (w << 2)
        M += ['; ---- %s, %%amode = %04X' % (name, v),
              '        mov a%d,0x%04X' % (r, dest), '        movhw a%d,0' % r,
              '        mov a0,0x0B00', '        movhw a0,0',
              '        mov.l r1,0x%04X' % (0x100 + 0x10 * c),
              '        mov.l r0,0x%04X' % v, '        mov %amode,r0', '        nop', '        nop']
