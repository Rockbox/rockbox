# t36_dma2: DWDMA DMEM -> SDRAM (channel 2) and SDRAM -> DMEM (channel 3)
# while the DSP uses the bus. Parameters from the ARM at DMEM 0x7F0:
#   [0] EPR index n of blocks A and B, [1] EPR value,
#   [2,3] A (source block, halfword k = k), [4,5] B (destination block),
#   [6,7] DSP window address of A, [8,9] DSP window address of B.
# Per case 8 words at OUT + 8*i: total cycles (DMA start -> done),
# cycles of the DSP's own bus accesses (0 if none), %loop1/%loop0 left in
# the completion poll (both FFFF = gave up), RawTfr, ChEnReg, mismatches,
# 0xC000 + i.
T36 = [  # (kind, words, CTL low, note)
    ('d2s', 16, 0x02002025, 'DMEM -> SDRAM, firmware settings (ch 2)'),
    ('d2s', 256, 0x02002025, 'DMEM -> SDRAM'),
    ('d2s', 1024, 0x02002025, 'DMEM -> SDRAM'),
    ('d2s', 1024, 0x02012025, 'DMEM -> SDRAM, source burst 32'),
    ('s2d', 1024, 0x00802025, 'SDRAM -> DMEM alone (ch 3)'),
    ('ld', 32, 0, '32 SDRAM loads alone'),
    ('s2d+ld', 1024, 0x00802025, 'SDRAM -> DMEM with 32 SDRAM loads during it'),
    ('st', 64, 0, '64 SDRAM std alone'),
    ('s2d+st', 1024, 0x00802025, 'SDRAM -> DMEM with 64 SDRAM std during it'),
]


def t36():
    def dw(name):
        return '0x%X' % (DW[name] // 2)

    def wr32(name, lo, hi):
        return ['        mov.l r4,0x%04X' % lo, '        mov.l r5,0x%04X' % hi,
                '        std r4,a2,%s' % dw(name)]

    def timer_start():
        return ['        mov.l r0,0xFFFF', '        mov %timer0,r0',
                '        nop', '        nop', '        nop', '        nop',
                '        mov r13,%timer0']

    def bus_ops(kind, n):
        if kind == 'ld':
            return ['        ld r1,a3,0x%X' % (0x400 + 0x10 * k) for k in range(n)] + ['        mov r1,r1']
        return ['        std r4,a4,0x%X' % (2 * k) for k in range(n)]
    L = ['; generated by gen_t21.py: DWDMA DMEM -> SDRAM, and DMA with concurrent DSP bus traffic',
         '        .equ TEST_ID, 0x0036'] + HEAD + ['        .include "prologue.inc"'] + PROLOGUE[2:]
    L += ['PARAM = DMEM_DSP + 0x7F0',
          'DEST = DMEM_DSP + 0x1000',
          '        mov a6,lo(EXTRA)', '        movhw a6,hi(EXTRA)',
          '        mov a1,lo(PARAM)', '        movhw a1,hi(PARAM)',
          '        ld r0,a1,0', '        ld r1,a1,1',
          '        ldd a3,a1,6',                                   # window address of A
          '        ldd a4,a1,8',                                   # window address of B
          '        mov n0,r0',
          '        mov a0,0x0000', '        movhw a0,0x00CE',
          '        nop', '        nop',
          '        stx r1,a0',                                     # EPR[n] for A/B
          '        mov.l r0,0x00C1', '        st r0,a0,3',        # EPR[3]: DWDMA
          '        mov a2,0x8000', '        movhw a2,0x00D7',
          '        mov.l r0,0x0080', '        mov %tc,r0']
    L += wr32('DmaCfgReg', 1, 0)
    for i, (kind, words, ctl, note) in enumerate(T36):
        hw = 2 * words
        L += ['; ---- %d: %s, %d words (%s)' % (i, kind, words, note),
              '        mov.l r0,%d' % i, '        st r0,a6,0',
              '        mov.l r11,0', '        mov.l r10,0', '        mov.l r9,0',
              '        mov.l r0,0xFFFF', '        mov.l r12,0xFFFF']
        if kind in ('ld', 'st'):
            L += timer_start() + bus_ops(kind, words) + [
                '        mov r14,%timer0', '        sub r13,r14', '        mov r12,r13',
                '        mov.l r13,0']
            L += st_out(['r13', 'r12', 'r10', 'r9', 'r9', 'r9', 'r11'])
            L += ['        mov.l r0,0x%04X' % (0xC000 + i), '        stu r0,a5,1']
            continue
        L += wr32('ClearTfr', 0x000F, 0) + wr32('ClearErr', 0x000F, 0) + wr32('ClearBlock', 0x000F, 0)
        a1p = ['        mov a1,lo(PARAM)', '        movhw a1,hi(PARAM)']
        if kind == 'd2s':
            ch, chen = 2, 0x0404
            # source DMEM 0x1000.. = k (written here), destination B
            L += ['        mov a1,lo(DEST)', '        movhw a1,hi(DEST)',
                  '        mov.l r0,0', '        mov.l r1,%d' % (hw - 1), '        mov %loop0,r1',
                  'f%d:     stu r0,a1,1' % i, '        add r0,1', '        agn0 f%d' % i]
            L += wr32('SAR2', 0x2000, 0x3000)
            L += a1p + ['        ldd r4,a1,4', '        std r4,a2,%s' % dw('DAR2')]
            L += wr32('LLP2', 0, 0) + wr32('CTL2', ctl & 0xFFFF, ctl >> 16) + wr32('CTL2H', words, 0)
            L += wr32('CFG2', 0x0040, 0) + wr32('CFG2H', 0x0004, 0)
        else:
            ch, chen = 3, 0x0808
            L += ['        mov a1,lo(DEST)', '        movhw a1,hi(DEST)',
                  '        mov.l r0,0', '        mov.l r1,%d' % (hw - 1), '        mov %loop0,r1',
                  'c%d:     stu r0,a1,1' % i, '        agn0 c%d' % i]
            L += a1p + ['        ldd r4,a1,2', '        std r4,a2,%s' % dw('SAR3')]
            L += wr32('DAR3', 0x2000, 0x3000) + wr32('LLP3', 0, 0)
            L += wr32('CTL3', ctl & 0xFFFF, ctl >> 16) + wr32('CTL3H', words, 0)
            L += wr32('CFG3', 0x0040, 0) + wr32('CFG3H', 0x0004, 0)
        L += ['        ldd r4,a2,%s' % dw('CTL2H'), '        mov r4,r4',       # drain the write buffer
              '        mov.l r0,15', '        mov %loop1,r0']
        L += timer_start()
        L += ['        mov.l r4,0x%04X' % chen, '        mov.l r5,0', '        std r4,a2,%s' % dw('ChEnReg')]
        if kind.endswith('+ld'):
            L += bus_ops('ld', 32) + ['        mov r12,%timer0']
        elif kind.endswith('+st'):
            L += ['        mov.l r4,0x5A5A', '        mov.l r5,0xA5A5'] + bus_ops('st', 64) + ['        mov r12,%timer0']
        if kind == 'd2s':
            # completion: RawTfr bit 2 (bus reads of the DMA register)
            L += ['        mov.l r8,%d' % (1 << ch),
                  'wo%d:    mov.l r0,0xFFFF' % i, '        mov %loop0,r0',
                  'w%d:     ldd r4,a2,%s' % (i, dw('RawTfr')),
                  '        and r4,r8', '        cmp r4,0', '        bnz d%d' % i,
                  '        agn0 w%d' % i, '        agn1 wo%d' % i]
        else:
            # completion: last destination halfword in DMEM holds its value
            L += ['        mov a1,lo(DEST + %d)' % (hw - 1), '        movhw a1,hi(DEST + %d)' % (hw - 1),
                  '        mov.l r8,%d' % (hw - 1),
                  'wo%d:    mov.l r0,0xFFFF' % i, '        mov %loop0,r0',
                  'w%d:     ld r1,a1' % i, '        cmp r1,r8', '        bz d%d' % i,
                  '        agn0 w%d' % i, '        agn1 wo%d' % i]
        L += ['d%d:     mov r14,%%timer0' % i,
              '        mov r1,r13', '        sub r13,r14',
              '        sub r1,r12', '        mov r12,r1',
              '        mov r10,%loop1', '        mov r9,%loop0']
        if not kind.endswith(('+ld', '+st')):
            L += ['        mov.l r12,0']
        L += ['        ldd r6,a2,%s' % dw('RawTfr'), '        ldd r4,a2,%s' % dw('ChEnReg'), '        mov r7,r4']
        L += wr32('ChEnReg', chen & 0xFF00, 0)                  # channel off if still running
        # verify
        if kind == 'd2s':
            L += ['        mov a1,lo(PARAM)', '        movhw a1,hi(PARAM)', '        ldd a0,a1,8',
                  '        mov.l r8,0', '        mov.l r11,0',
                  '        mov.l r1,%d' % (words - 1), '        mov %loop0,r1',
                  'v%d:     ldd r4,a0' % i, '        add a0,2',
                  '        cmp r4,r8', '        bz o%d' % i, '        add r11,1',
                  'o%d:     add r8,1' % i, '        cmp r5,r8', '        bz p%d' % i, '        add r11,1',
                  'p%d:     add r8,1' % i, '        agn0 v%d' % i,
                  '        mov a0,0x0000', '        movhw a0,0x00CE']
        else:
            L += ['        mov a1,lo(DEST)', '        movhw a1,hi(DEST)',
                  '        mov.l r8,0', '        mov.l r11,0',
                  '        mov.l r1,%d' % (hw - 1), '        mov %loop0,r1',
                  'v%d:     ldu r1,a1,1' % i, '        cmp r1,r8', '        bz o%d' % i, '        add r11,1',
                  'o%d:     add r8,1' % i, '        agn0 v%d' % i]
        L += st_out(['r13', 'r12', 'r10', 'r9', 'r6', 'r7', 'r11'])
        L += ['        mov.l r0,0x%04X' % (0xC000 + i), '        stu r0,a5,1']
    L += marker(0xE36D)
    L.append('        .include "epilogue.inc"')
    return L


