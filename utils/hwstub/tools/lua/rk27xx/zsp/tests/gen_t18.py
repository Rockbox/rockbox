"""Generate t18_cp_<n>.s: one coprocessor instruction each, between two markers
(EXTRA+0 = 0x1111 before, EXTRA+1 = 0x2222 after). Run separately: may hang."""
import json

CP = ['cpcom r4,0x1234', 'cpcom a2,0x0001', 'cpcom.e r0,0x0000', 'cpcom a2,a3,0x0000', 'cpcom.e r0,a2,0x0000',
      'cpout 0x0000', 'cpout.e r0,0x0000', 'cpout a2,a3,0x0000', 'cpout.e r0,a2,0x0000']


def main():
    for i, ins in enumerate(CP):
        L = ['; generated by gen_t18.py: %s' % ins, '        .equ TEST_ID, 0x0180 + %d' % i,
             '        .include "common.inc"', '        .include "prologue.inc"',
             '        mov.l r0,0x0100', '        mov.l r1,0x0200', '        mov.l r4,0x4444',
             '        mov a2,lo(SCRATCH)', '        movhw a2,hi(SCRATCH)',
             '        mov a3,lo(SCRATCH + 8)', '        movhw a3,hi(SCRATCH + 8)',
             '        mov.l r13,0x1111', '        st r13,a7,0x40',
             '        ' + ins, '        nop', '        nop',
             '        mov.l r13,0x2222', '        st r13,a7,0x41',
             '        .include "epilogue.inc"']
        open('t18_cp_%d.s' % i, 'w').write('\n'.join(L) + '\n')
    json.dump(CP, open('t18_cp.json', 'w'))
    print('%d coprocessor tests' % len(CP))


main()
