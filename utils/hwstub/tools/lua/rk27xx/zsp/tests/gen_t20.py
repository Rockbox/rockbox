"""
Generate t20_final.s + t20_final.json: last open questions.
Each case: setup, sequence, then IMMEDIATELY mov r15,%hwflag / mov r12,%shwflag,
then record items. Results at SCRATCH + 0x100: hwflag, shwflag, items..., marker.
"""
import json

cases = []


def case(name, setup, seq, rec, note):
    cases.append({'name': name, 'setup': setup, 'seq': seq, 'rec': rec, 'note': note})


# compare variants: r4 = -3 vs 5 style operands -> expect lt (flags 0) or gt (0x70)
for ins, setup, note in [
        ('cmp r4,r5', ['mov.l r4,0xFFFD', 'mov.l r5,5'], '-3 vs 5: lt'),
        ('cmp r5,r4', ['mov.l r4,0xFFFD', 'mov.l r5,5'], '5 vs -3: gt'),
        ('cmp.e r8,1', ['mov.l r8,0', 'mov.l r9,1'], '0x10000 vs 1: gt'),
        ('cmp.e r8,-1', ['mov.l r8,0xFFFF', 'mov.l r9,0xFFFF'], '-1 vs -1: eq'),
        ('cmp a2,0', ['mov a2,0', 'movhw a2,0'], '0 vs 0: eq'),
        ('cmp a2,1', ['mov a2,0', 'movhw a2,0x0010'], '0x100000 vs 1: gt'),
        ('cmp n1,1', ['mov n1,0xFFFF'], '-1 vs 1: lt'),
        ('cmp n1,r5', ['mov n1,7', 'mov.l r5,5'], '7 vs 5: gt'),
        ('cmp.e a2,r8', ['mov a2,0', 'movhw a2,1', 'mov.l r8,0', 'mov.l r9,1'], '0x10000 vs 0x10000: eq'),
        ('cmp.e r8,r10', ['mov.l r8,0', 'mov.l r9,1', 'mov.l r10,0xFFFF', 'mov.l r11,0'], '0x10000 vs 0xFFFF: gt'),
        ('cmp.f r8,r10', ['mov.l r8,0', 'mov.l r9,0', 'mov g4,1', 'mov.l r10,0', 'mov.l r11,0', 'mov g5,0'],
         '2^32 (guard) vs 0: gt'),
        ('cmp r4,1000', ['mov.l r4,1000'], 'eq'),
        ('cmp.e r8,1000', ['mov.l r8,1000', 'mov.l r9,0'], 'eq'),
        ('cmp.f r8,r10', ['mov.l r8,0', 'mov.l r9,0', 'mov g4,0', 'mov.l r10,0', 'mov.l r11,0', 'mov g5,0'], 'eq')]:
    case('C ' + ins + ' ' + note, setup, [ins], [], note)
# flag/shadow register writes
case('W mov %hwflag,r', ['mov.l r5,0x0008'], ['mov %hwflag,r5'], [], 'write 0x0008 (Z) via 79xx')
case('W mov %shwflag,r', ['mov.l r5,0x0040'], ['mov %shwflag,r5'], [], 'write 0x0040 via 79xx')
case('W bits %hwflag,3', ['mov.l r4,1', 'cmp r4,0'], ['bits %hwflag,3'], [], 'set Z by bit op')
case('W bitc %hwflag,6', ['mov.l r4,1', 'cmp r4,0'], ['bitc %hwflag,6'], [], 'clear C by bit op')
case('W bitc %hwflag,8', ['mov.l r4,0x7FFF', 'add r4,r4'], ['bitc %hwflag,8'], [], 'clear sticky overflow')
# cexe u/nu and cexe/cexes: Z = 1 before; shadow = cmp (clears Z), add r5,1
for kind in ['cexe', 'cexes']:
    for u in ['u', 'nu']:
        case('X %s (z,%s)' % (kind, u), ['mov.l r4,0', 'mov.l r5,0', 'cmp r4,0'],
             ['%s (z,%s) { } !2' % (kind, u), 'cmp r4,1', 'add r5,1'], ['r5'],
             'Z=1 before; shadow: cmp r4,1 (Z->0), add r5,1. r5 = 0 if the condition is re-checked; flags show if cmp updated them')
# vxor after Viterbi decisions
case('V vxor r12', ['mov.l r12,0x00FF', 'mov.l r8,3', 'mov.l r9,4', 'mov.l r10,5', 'mov.l r11,6',
                    'vit_a r2,r8,r10', 'vit_b r2,r8,r10'], ['vxor r12'], ['r12', '%vitr'], 'r12 = 0x00FF')
case('V vxor.e r8', ['mov.l r8,0x00FF', 'mov.l r9,0x0F0F'], ['vxor.e r8'], ['r8', 'r9', '%vitr'], 'pair 0x0F0F00FF')
case('V vit_a decisions', ['mov.l r8,9', 'mov.l r9,1', 'mov.l r10,1', 'mov.l r11,1'],
     ['vit_a r2,r8,r10'], ['r2', '%vitr'], '9+1=10 vs 1+1=2: second smaller')


def main():
    L = ['; generated by gen_t20.py', '        .equ TEST_ID, 0x0020', '        .include "common.inc"',
         'OUT = SCRATCH + 0x100', '        .include "prologue.inc"',
         '        mov a5,lo(OUT)', '        movhw a5,hi(OUT)']
    off = 0
    for i, c in enumerate(cases):
        L.append('; ---- %d %s' % (i, c['name']))
        L += ['        ' + x for x in c['setup']]
        L += ['        nop'] * 4
        L += ['        ' + x for x in c['seq']]
        L += ['        mov r15,%hwflag', '        mov r12,%shwflag' if 'r12' not in c['rec'] else '        nop']
        L += ['        stu r15,a5,1']
        L += ['        stu r12,a5,1']
        for it in c['rec']:
            L += (['        stu %s,a5,1' % it] if it[0] == 'r' else ['        mov r13,%s' % it, '        stu r13,a5,1'])
        L += ['        mov.l r13,0x%04X' % (0xC000 + i), '        stu r13,a5,1']
        c['off'] = off
        off += 3 + len(c['rec'])
    L.append('        .include "epilogue.inc"')
    open('t20_final.s', 'w').write('\n'.join(L) + '\n')
    json.dump(cases, open('t20_final.json', 'w'), indent=1)
    print('%d cases' % len(cases))


main()
