"""
Generate t17_circ.s + t17_circ.json: which %amode bits enable circular
buffers. %cbK_beg = S+0x10+0x10K, %cbK_end = beg+3; aK = beg; then 6 x
'ldu r4,aK,1' for K = 0..3 with %amode = value, %amode back to 0, store the
low half of a0..a3 and %amode read-back to EXTRA (st, no post-modify).
Linear: aK = beg+6. Wrapping on a 4-entry buffer: beg+2 (or beg+1/+3).
"""
import json

VALS = [0] + [1 << k for k in range(16)]
# multi-bit codes (t17 found no single bit that enables wrapping)
VALS2 = [0x0003, 0x000C, 0x0030, 0x0060, 0x0300, 0x0C00, 0x0007, 0x0038, 0x000F, 0x00F0, 0x0F00,
         0x007F, 0x0F7F, 0x1111, 0x2222, 0x0555, 0x0AAA]
import sys
if len(sys.argv) > 1 and sys.argv[1] == 'b':
    VALS = VALS2


def main():
    L = ['; generated by gen_t17.py', '        .equ TEST_ID, 0x0017 + (len(sys.argv) > 1)' if False else '        .equ TEST_ID, 0x0017', '        .include "common.inc"',
         '        .include "prologue.inc"']
    for k in range(4):
        L += ['        mov.l r0,lo(SCRATCH + 0x%X)' % (0x10 + 0x10 * k), '        mov %%cb%d_beg,r0' % k,
              '        mov.l r0,lo(SCRATCH + 0x%X)' % (0x13 + 0x10 * k), '        mov %%cb%d_end,r0' % k]
    slot = 0x40
    for v in VALS:
        L.append('; ---- amode = 0x%04X' % v)
        for k in range(4):
            L += ['        mov a%d,lo(SCRATCH + 0x%X)' % (k, 0x10 + 0x10 * k),
                  '        movhw a%d,hi(SCRATCH + 0x%X)' % (k, 0x10 + 0x10 * k)]
        L += ['        mov.l r0,0x%04X' % v, '        mov %amode,r0', '        nop', '        nop',
              '        mov r5,%amode']
        for _ in range(6):
            L += ['        ldu r4,a%d,1' % k for k in range(4)]
        L += ['        mov.l r0,0', '        mov %amode,r0', '        nop', '        nop']
        for k in range(4):
            L += ['        movlw r6,a%d' % k, '        st r6,a7,0x%X' % slot]
            slot += 1
        L += ['        st r5,a7,0x%X' % slot]
        slot += 1
    L.append('        .include "epilogue.inc"')
    out = 't17b_circ' if len(sys.argv) > 1 and sys.argv[1] == 'b' else 't17_circ'
    open(out + '.s', 'w').write('\n'.join(L) + '\n')
    json.dump(VALS, open(out + '.json', 'w'))
    print('%d amode values, slots up to 0x%X' % (len(VALS), slot))


main()
