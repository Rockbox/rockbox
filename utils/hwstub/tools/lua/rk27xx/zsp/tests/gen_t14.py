"""
Generate t14_settle.s + t14_settle.json: follow-up to t13.
Records r0..r7, cycles and a marker (10 halfwords per case) at SCRATCH + 0x100.
"""
import json

BASE = {'r0': 0x0000, 'r1': 0x0000, 'r2': 0x0200, 'r3': 0x0300,
        'r4': 0xFFFD, 'r5': 0x0005, 'r6': 0x0007, 'r7': 0xFFFE,
        'r8': 0x0003, 'r9': 0x0004, 'r10': 0x0005, 'r11': 0x0006, 'r12': 0xA5C3}
cases = []


def case(name, insn, note, **regs):
    r = dict(BASE)
    r.update(regs)
    cases.append({'name': name, 'insn': [insn], 'note': note, 'regs': r})


# 16-bit ext/exts: spec word in the odd register of the destination pair?
case('ext16_r1_0408', 'ext r0,r12', 'r1 = 0x0408 -> 0x005C if spec in r1', r1=0x0408)
case('ext16_r1_0804', 'ext r0,r12', 'r1 = 0x0804 -> 0x0005', r1=0x0804)
case('exts16_r1_0C04', 'exts r0,r12', 'r1 = 0x0C04 -> 0xFFFA', r1=0x0C04)
case('ext16_ctl', 'ext r0,r12', 'control: r1 = 0, r3 = 0x0408 -> 0 if spec is r1', r1=0x0000, r3=0x0408)
case('ext16_r2pair', 'ext r2,r12', 'dest pair r2:r3, r3 = 0x0408 -> r2 = 0x005C', r2=0, r3=0x0408)
case('ext16e_r1_1008', 'ext.e r0,r8', 'pair 0x12345678, r1 = 0x1008 -> 0x0034', r1=0x1008, r8=0x5678, r9=0x1234)
case('exts16e_r1_1C04', 'exts.e r0,r8', 'pair 0x92345678, r1 = 0x1C04 -> 0xFFF9', r1=0x1C04, r8=0x5678, r9=0x9234)
# register-spec 32-bit pair forms not yet verified
case('extre_1008', 'ext.e r0,r8,r5', 'pair 0x12345678, r5 = 0x1008 -> 0x0034', r5=0x1008, r8=0x5678, r9=0x1234)
case('extsre_1C04', 'exts.e r0,r8,r5', 'pair 0x92345678, r5 = 0x1C04 -> 0xFFF9', r5=0x1C04, r8=0x5678, r9=0x9234)
case('insre_1008', 'ins.e r0,r12,r5', 'into 0xFFFFFFFF, r5 = 0x1008 -> r1 = 0xFFC3', r0=0xFFFF, r1=0xFFFF, r5=0x1008)
# imulc r2,rb,rc (87xx): where does the result go?
case('imulc87_45', 'imulc r2,r4,r5', '-3 x 5 = 0xFFF1; record r0..r7')
case('imulc87_8a', 'imulc r2,r8,r10', '3 x 5 = 0x000F; record r0..r7')
case('imulc87_67', 'imulc r2,r6,r7', '7 x -2 = 0xFFF2; record r0..r7')


def main():
    L = ['; generated by gen_t14.py: follow-up to t13',
         '        .equ TEST_ID, 0x0014',
         '        .include "common.inc"',
         'OUT = SCRATCH + 0x100',
         '        .include "prologue.inc"',
         '        mov.l r0,0x0080',
         '        mov %tc,r0',
         '        mov a5,lo(OUT)',
         '        movhw a5,hi(OUT)']
    for i, cs in enumerate(cases):
        L.append('; ---- %d %s: %s' % (i, cs['name'], cs['note']))
        regs = dict(cs['regs'])
        r13 = regs.pop('r13', None)
        for r in ['r%d' % k for k in range(13)]:
            L.append('        mov.l %s,0x%04X' % (r, regs[r]))
        L += ['        nop'] * 4
        if r13 is not None:
            L.append('        mov.l r13,0x%04X' % r13)
            L += ['        nop'] * 4
        L.append('        mov r13,%timer0')
        L += ['        ' + x for x in cs['insn']]
        L.append('        mov r14,%timer0')
        L += ['        nop'] * 4
        L.append('        sub r13,r14')
        L += ['        stu r%d,a5,1' % k for k in range(8)]
        L += ['        stu r13,a5,1', '        mov.l r14,0x%04X' % (0xC000 + i), '        stu r14,a5,1']
    L.append('        .include "epilogue.inc"')
    open('t14_settle.s', 'w').write('\n'.join(L) + '\n')
    json.dump(cases, open('t14_settle.json', 'w'), indent=1)
    print('%d cases' % len(cases))


if __name__ == '__main__':
    main()
