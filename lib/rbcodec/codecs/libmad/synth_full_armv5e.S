/*
 * Inner loops of synth_full() for ARMv5E and later (see synth.c), one per
 * value of phase & 3, which fixes where in the packed 16-bit window each
 * coefficient sits.  Each iteration makes
 *
 *   pcm[-sb] = fe . E + fo . O      and      pcm[sb] = fe . Ro + fo . Re
 *
 * loading each filter value once for both sums (O holds the window negated).
 * The code was generated by
 * a script that places each coefficient load ahead of its use.
 *
 *   r0 = pcm, the start of the 32 samples of the time slot
 *   r1 = fo, for sb = 15
 *   r2 = fe, for sb = 15
 *   r3 = window row 1 of Dpk, at the word holding halfword (p / 2) & ~1
 */

#include "config.h"
#include "mad_iram.h"

#define DPK_ROW_BYTES (4 * 16 * 2)

    .syntax     unified
    .section    ICODE_SECTION_MPA_ARM,"ax",%progbits

/* phase & 3 == 0: o = 0, al = 1 */
    .global synth_full_armv5e_0
    .type   synth_full_armv5e_0, %function
synth_full_armv5e_0:
    stmfd   sp!, {r4-r11, lr}
    add     r12, r0, #31*4      /* pcm[sb], sb = 15 */
    add     r0, r0, #1*4        /* pcm[-sb] */
.Lloop0:
    ldmia   r1!, {r6-r9}
    ldr     r10, [r3, #0]
    ldr     r11, [r3, #112]
    ldr     lr, [r3, #16]
    smulwt  r4, r6, r10
    ldr     r10, [r3, #12]
    smulwt  r5, r6, r11
    smlawb  r4, r7, lr, r4
    ldr     lr, [r3, #108]
    smlawb  r5, r7, r11, r5
    ldr     r11, [r3, #8]
    smlawt  r4, r8, r10, r4
    smlawt  r5, r8, lr, r5
    smlawb  r4, r9, r10, r4
    ldr     r10, [r3, #104]
    smlawb  r5, r9, lr, r5
    ldmia   r1!, {r6-r9}
    ldr     lr, [r3, #4]
    smlawt  r4, r6, r11, r4
    smlawt  r5, r6, r10, r5
    smlawb  r4, r7, r11, r4
    ldr     r11, [r3, #100]
    smlawb  r5, r7, r10, r5
    ldr     r10, [r3, #36]
    smlawt  r4, r8, lr, r4
    smlawt  r5, r8, r11, r5
    smlawb  r4, r9, lr, r4
    ldr     lr, [r3, #64]
    smlawb  r5, r9, r11, r5
    ldmia   r2!, {r6-r9}
    ldr     r11, [r3, #48]
    smlawb  r4, r6, r10, r4
    smlawt  r5, r6, lr, r5
    ldr     lr, [r3, #80]
    smlawt  r4, r7, r11, r4
    smlawb  r5, r7, lr, r5
    ldr     lr, [r3, #76]
    smlawb  r4, r8, r11, r4
    ldr     r11, [r3, #44]
    smlawt  r5, r8, lr, r5
    smlawt  r4, r9, r11, r4
    smlawb  r5, r9, lr, r5
    ldmia   r2!, {r6-r9}
    ldr     lr, [r3, #72]
    smlawb  r4, r6, r11, r4
    ldr     r11, [r3, #40]
    smlawt  r5, r6, lr, r5
    smlawt  r4, r7, r11, r4
    smlawb  r5, r7, lr, r5
    ldr     lr, [r3, #68]
    smlawb  r4, r8, r11, r4
    smlawt  r5, r8, lr, r5
    smlawt  r4, r9, r10, r4
    smlawb  r5, r9, lr, r5
    mov     r4, r4, lsl #2
    mov     r5, r5, lsl #2
    str     r4, [r0], #4
    str     r5, [r12], #-4
    add     r3, r3, #DPK_ROW_BYTES
    cmp     r0, r12
    bne     .Lloop0
    ldmfd   sp!, {r4-r11, pc}
    .size   synth_full_armv5e_0, .-synth_full_armv5e_0

